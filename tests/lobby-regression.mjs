import fs from 'node:fs';
import assert from 'node:assert/strict';
import {runInNewContext} from 'node:vm';
const html=fs.readFileSync(new URL('../index.html',import.meta.url),'utf8');
const script=html.match(/<script>([\s\S]*?)<\/script>/)[1];
const api=runInNewContext(script.split('const $=id=>')[0]+'\n({recentGames,categoryMatches,dodgeRecords})');
const allowed=['reaction','aim','memory','sequence','odd','dodge'];
assert.deepEqual([...api.recentGames('["odd","odd","constructor","aim","dodge","memory","reaction"]',allowed)],['odd','aim','dodge','memory']);
for(const bad of ['null','{}','[1,null,"__proto__"]','<script>','"odd"'])assert.equal(api.recentGames(bad,allowed).length,0);
assert.ok(api.categoryMatches('memory leisure','memory'));assert.ok(api.categoryMatches('memory leisure','leisure'));
assert.equal(api.categoryMatches('memory leisure','reaction'),false);assert.ok(api.categoryMatches('', 'all'));
const records=api.dodgeRecords('42','{"1":30,"free:1":29.5,"2":50,"99":100,"3":"NaN","free:2":-1,"__proto__":100}');
assert.equal(records.length,3);assert.ok(records.some(text=>text.includes('经典 · L1 起步 · 42.0')));
assert.ok(records.some(text=>text.includes('自由 · L1 起步 · 29.5')));
assert.equal(api.dodgeRecords(null,'not-json').length,0);
for(const value of ['NaN','Infinity','-1'])assert.equal(api.dodgeRecords(value,'{}').length,0);
for(const name of ['reaction','memory','observation','logic','leisure'])assert.ok(html.includes(`data-filter="${name}"`));
assert.match(html,/id="recentList"/);assert.match(html,/id="records"/);
assert.match(script,/if\(!dialog.open&&currentGame\)showLobby\(\)/,'Queued close from a previous game must not close a newly opened game');
assert.doesNotMatch(script,/savedMode/,'A previous saved difficulty must not override the single default mode');
assert.doesNotMatch(html,/轻松玩|挑战一下|data-mode=/,'The lobby dialog must not expose global mode choices');
assert.match(script,/renderClassicResult\(`\$\{score\} ms/);
assert.match(script,/renderClassicResult\(`\$\{score\} 分/);
assert.match(script,/renderClassicResult\(`完成 · \$\{steps\} 步/);
console.log('Lobby regression passed: safe recent history, multi-category filtering, unchanged legacy record reads and result integration');
